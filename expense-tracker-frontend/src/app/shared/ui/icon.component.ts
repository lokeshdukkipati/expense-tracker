/** Names the backend sends (for example badge icons) that differ from ours. */
const ALIASES: Record<string, IconName> = {
  'trend-up': 'trending-up',
  'trend-down': 'trending-down',
  bank: 'landmark',
};

/** Turns any icon name from data into one we can draw, so an unknown name can never break a screen. */
export function iconOr(
  name: string | null | undefined,
  fallback: IconName = 'sparkles',
): IconName {
  if (!name) return fallback;
  if (Object.prototype.hasOwnProperty.call(ICONS, name))
    return name as IconName;
  return ALIASES[name] ?? fallback;
}

